import { formatMoney } from "../money";
import { createPdf } from "./pdfDocument";

export interface PayslipPdfData {
  business: { name: string; address: string | null; phone: string | null };
  currencySymbol: string;
  currencyCode: string;
  code: string;
  runCode: string;
  period: string;
  payDate: string;
  employee: { code: string; name: string; jobTitle: string | null; bankName: string | null; bankAccountNumber: string | null; bankAccountName: string | null };
  earnings: Array<{ label: string; amount: number }>;
  deductions: Array<{ label: string; amount: number }>;
  grossPay: number;
  totalDeductions: number;
  netPay: number;
  amountPaid: number;
  payments: Array<{ date: string; method: string; reference: string | null; amount: number }>;
  attendance: { daysLate: number; daysAbsent: number };
}

export async function renderPayslip(data: PayslipPdfData): Promise<Buffer> {
  const handle = createPdf({ title: `Payslip ${data.code}`, size: "A5", margin: 32 });
  const { doc } = handle;
  const m = (v: number) => formatMoney(v, handle.unicode ? data.currencySymbol : `${data.currencyCode} `);
  const left = doc.page.margins.left;
  const usable = doc.page.width - left - doc.page.margins.right;

  const row = (label: string, value: string, bold = false) => {
    const y = doc.y;
    doc.font(bold ? handle.bold : handle.regular).fontSize(bold ? 10 : 9).fillColor("#0f172a");
    doc.text(label, left, y, { width: usable * 0.6 });
    doc.text(value, left + usable * 0.4, y, { width: usable * 0.6, align: "right" });
    doc.moveDown(0.2);
  };
  const heading = (text: string) => {
    doc.moveDown(0.5).font(handle.bold).fontSize(9).fillColor("#64748b").text(text.toUpperCase(), left, doc.y, { width: usable });
    doc.moveTo(left, doc.y + 2).lineTo(left + usable, doc.y + 2).lineWidth(0.5).strokeColor("#e2e8f0").stroke();
    doc.moveDown(0.4);
  };

  doc.font(handle.bold).fontSize(14).fillColor("#0f172a").text(data.business.name);
  doc.font(handle.regular).fontSize(8).fillColor("#64748b");
  if (data.business.address) doc.text(data.business.address);
  if (data.business.phone) doc.text(data.business.phone);
  doc.moveDown(0.6).font(handle.bold).fontSize(12).fillColor("#0f172a").text("PAYSLIP");
  doc.font(handle.regular).fontSize(8).fillColor("#475569").text(`${data.code} · ${data.runCode} · Pay date ${data.payDate}`);

  heading("Employee");
  row("Name", data.employee.name);
  row("Staff no.", data.employee.code);
  if (data.employee.jobTitle) row("Role", data.employee.jobTitle);
  row("Pay period", data.period);
  if (data.employee.bankName) row("Bank", `${data.employee.bankName}${data.employee.bankAccountNumber ? ` · ${data.employee.bankAccountNumber}` : ""}`);

  heading("Earnings");
  for (const e of data.earnings) row(e.label, m(e.amount));
  row("Gross pay", m(data.grossPay), true);

  heading("Deductions");
  if (data.deductions.length === 0) row("None", m(0));
  for (const d of data.deductions) row(d.label, m(d.amount));
  row("Total deductions", m(data.totalDeductions), true);

  heading("Net pay");
  row("Net pay", m(data.netPay), true);
  for (const p of data.payments) row(`Paid ${p.date} (${p.method}${p.reference ? ` · ${p.reference}` : ""})`, m(p.amount));
  if (data.netPay - data.amountPaid > 0) row("Still owed", m(data.netPay - data.amountPaid), true);

  if (data.attendance.daysLate > 0 || data.attendance.daysAbsent > 0) {
    doc.moveDown(0.5).font(handle.regular).fontSize(8).fillColor("#64748b").text(`Attendance this period: ${data.attendance.daysLate} late, ${data.attendance.daysAbsent} absent.`, left);
  }
  doc.moveDown(1).font(handle.regular).fontSize(7).fillColor("#94a3b8").text("This payslip was generated by ShowroomPro.", left, doc.y, { width: usable, align: "center" });
  return handle.done();
}
